const base = "http://127.0.0.1:4101";
const post = (path, body, token) => fetch(`${base}${path}`, { method: "POST", headers: { "content-type": "application/json", ...(token ? { authorization: `Bearer ${token}` } : {}) }, body: JSON.stringify(body) });
const patch = (path, body, token) => fetch(`${base}${path}`, { method: "PATCH", headers: { "content-type": "application/json", authorization: `Bearer ${token}` }, body: JSON.stringify(body) });
const login = await post("/api/auth/login", { email: "ivan.petrov@moex.dev", password: "Demo12345" }).then((r) => r.json());
const token = login.token;
const dashboard = await fetch(`${base}/api/dashboard`, { headers: { authorization: `Bearer ${token}` } }).then((r) => r.json());
console.log("cash", dashboard.cash, "equity", dashboard.equity, "positionsValue", dashboard.totals.value);
const buy = await post("/api/orders", { ticker: "GAZP", side: "buy", qty: 10 }, token).then((r) => r.json());
console.log("buy", buy.operation?.kind, buy.operation?.amount, "cash", buy.cash);
const lot = await post("/api/orders", { ticker: "GAZP", side: "buy", qty: 3 }, token);
console.log("lot", lot.status, (await lot.json()).error);
const sellTooMuch = await post("/api/orders", { ticker: "GAZP", side: "sell", qty: 100000 }, token);
console.log("sell", sellTooMuch.status, (await sellTooMuch.json()).error);
const sell = await post("/api/orders", { ticker: "GAZP", side: "sell", qty: 10 }, token).then((r) => r.json());
console.log("sell ok cash", sell.cash, "position", sell.position?.qty);
const deposit = await post("/api/deposit", { amount: 5000 }, token).then((r) => r.json());
console.log("deposit", deposit.ok, "cash", deposit.cash);
const profile = await patch("/api/profile", { name: "Иван П." }, token).then((r) => r.json());
console.log("profile", profile.name, profile.role);
const badDeposit = await post("/api/deposit", { amount: 1 }, token);
console.log("bad deposit", badDeposit.status, (await badDeposit.json()).error);
const after = await fetch(`${base}/api/dashboard`, { headers: { authorization: `Bearer ${token}` } }).then((r) => r.json());
console.log("after cash", after.cash, "equity", after.equity);
process.exit(0);
